#include "Keyboard.h"

#include <array>

namespace {
// MapVirtualKey(vk, MAPVK_VK_TO_VSC) for the US layout.
constexpr std::array<quint8, 256> makeVkToScan()
{
    std::array<quint8, 256> t{};
    const char *letters = "\x1e\x30\x2e\x20\x12\x21\x22\x23\x17\x24\x25\x26\x32\x31\x18\x19\x10\x13\x1f\x14\x16\x2f\x11\x2d\x15\x2c";
    for (int i = 0; i < 26; ++i) t['A' + i] = quint8(letters[i]);
    const char *digits = "\x0b\x02\x03\x04\x05\x06\x07\x08\x09\x0a";
    for (int i = 0; i < 10; ++i) t['0' + i] = quint8(digits[i]);
    for (int i = 0; i < 10; ++i) t[0x70 + i] = quint8(0x3B + i);   // F1..F10
    t[0x7A] = 0x57; t[0x7B] = 0x58;                                  // F11, F12
    t[0x08] = 0x0E; t[0x09] = 0x0F; t[0x0D] = 0x1C; t[0x10] = 0x2A; t[0x11] = 0x1D; t[0x12] = 0x38;
    t[0x13] = 0x45; t[0x14] = 0x3A; t[0x1B] = 0x01; t[0x20] = 0x39;
    t[0x21] = 0x49; t[0x22] = 0x51; t[0x23] = 0x4F; t[0x24] = 0x47;
    t[0x25] = 0x4B; t[0x26] = 0x48; t[0x27] = 0x4D; t[0x28] = 0x50;
    t[0x2C] = 0x54; t[0x2D] = 0x52; t[0x2E] = 0x53; t[0x5B] = 0x5B; t[0x5C] = 0x5C; t[0x5D] = 0x5D;
    const quint8 numpad[10] = {0x52, 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49};
    for (int i = 0; i < 10; ++i) t[0x60 + i] = numpad[i];
    t[0x6A] = 0x37; t[0x6B] = 0x4E; t[0x6D] = 0x4A; t[0x6E] = 0x53; t[0x6F] = 0x35;
    t[0x90] = 0x45; t[0x91] = 0x46;
    t[0xA0] = 0x2A; t[0xA1] = 0x36; t[0xA2] = 0x1D; t[0xA3] = 0x1D; t[0xA4] = 0x38; t[0xA5] = 0x38;
    t[0xBA] = 0x27; t[0xBB] = 0x0D; t[0xBC] = 0x33; t[0xBD] = 0x0C; t[0xBE] = 0x34; t[0xBF] = 0x35;
    t[0xC0] = 0x29; t[0xDB] = 0x1A; t[0xDC] = 0x2B; t[0xDD] = 0x1B; t[0xDE] = 0x28; t[0xE2] = 0x56;
    return t;
}
constexpr auto kVkToScan = makeVkToScan();
}

quint8 Keyboard::vkToScan(quint8 vk)
{
    return kVkToScan[vk];
}
