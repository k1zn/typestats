quint8 Keyboard::scanToVk(ScanCode scan, bool numLock)
{
    if (!scan.extended && scan.code >= 0x47 && scan.code <= 0x53)
        if (const quint8 vk = (numLock ? kPadOn : kPadOff)[scan.code - 0x47])
            return vk;
    const ScanVk *first = scan.extended ? std::begin(kExtended) : std::begin(kPlain);
    const ScanVk *last = scan.extended ? std::end(kExtended) : std::end(kPlain);
    for (const ScanVk *e = first; e != last; ++e)
        if (e->scan == scan.code)
            return e->vk;
    return 0;
}

std::optional<Keyboard::ScanCode> Keyboard::evdevToScan(int code)
{
    if (code == 69) // KEY_NUMLOCK: extended at Windows' hook, unlike Pause
        return ScanCode{0x45, true};
    if (code >= 1 && code <= 83)
        return ScanCode{quint8(code), false};
    for (const EvdevScan &e : kEvdev)
        if (e.code == code)
            return ScanCode{e.scan, e.extended};
    return std::nullopt;
}

int Keyboard::scanToEvdev(ScanCode scan)
{
    if (scan == ScanCode{0x45, true})
        return 69;
    for (const EvdevScan &e : kEvdev)
        if (e.scan == scan.code && e.extended == scan.extended)
            return e.code;
    if (!scan.extended && scan.code >= 1 && scan.code <= 83)
        return scan.code;
    return -1;
}
